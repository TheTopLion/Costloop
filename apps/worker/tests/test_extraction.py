from decimal import Decimal

import pytest

from appraise_worker.extraction import ExtractionValidationError, FakeTableProvider, extract_draft
from appraise_worker.extraction_models import QuoteDraft
from appraise_worker.ingestion import CellEvidence, ParsedDocument, SheetEvidence


def table_document() -> ParsedDocument:
    values = [
        ("A1", "Position"), ("B1", "Description"), ("C1", "Quantity"), ("D1", "Unit"),
        ("E1", "Price"), ("F1", "Total"), ("G1", "Currency"),
        ("A2", "10"), ("B2", "Steel plate"), ("C2", "2.5"), ("D2", "kg"),
        ("E2", "4.00"), ("F2", "10.00"), ("G2", "USD"),
    ]
    return ParsedDocument("quote.xlsx", "application/xlsx", sheets=(
        SheetEvidence("Quote", tuple(CellEvidence(coordinate, value) for coordinate, value in values), ()),
    ))


def test_fake_table_provider_returns_decimal_quote_with_provenance() -> None:
    result = extract_draft(FakeTableProvider(), "quote", table_document())
    assert isinstance(result, QuoteDraft)
    assert result.lines[0].quantity == Decimal("2.5")
    assert result.lines[0].source.cell_range == "'Quote'!A2:G2"
    assert result.warnings[0].startswith("Generated by FAKE deterministic table provider")


def test_schema_rejects_negative_money_and_warns_on_inconsistent_total() -> None:
    payload = FakeTableProvider().extract("quote", table_document())
    payload["lines"][0]["unit_price"] = "5"
    result = QuoteDraft.model_validate(payload)
    assert any("differs" in warning for warning in result.warnings)
    payload["lines"][0]["unit_price"] = "-1"
    with pytest.raises(ValueError):
        QuoteDraft.model_validate(payload)


class RetryingProvider:
    def __init__(self, valid_on: int) -> None:
        self.calls = 0
        self.valid_on = valid_on
        self.feedback: list[str | None] = []

    def extract(self, kind, document, validation_feedback=None):
        self.calls += 1
        self.feedback.append(validation_feedback)
        if self.calls < self.valid_on:
            return {"document_kind": kind, "lines": [{"quantity": "-1"}]}
        return FakeTableProvider().extract(kind, document)


def test_validation_retry_is_bounded_and_supplies_feedback() -> None:
    provider = RetryingProvider(valid_on=2)
    extract_draft(provider, "specification", table_document(), max_attempts=2)
    assert provider.calls == 2 and provider.feedback[1]
    with pytest.raises(ExtractionValidationError, match="after 2 attempts"):
        extract_draft(RetryingProvider(valid_on=3), "specification", table_document(), max_attempts=2)
